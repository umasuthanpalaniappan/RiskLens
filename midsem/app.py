# Data helpers
# ─────────────────────────────────────────────────────────────
@st.cache_data(ttl=300, show_spinner="Fetching live stock data...")
def fetch_overview():
    rows = []
    for t in TICKERS:
        row = {"Ticker": t.replace(".NS", ""), "Company": NAMES[t]}
        try:
            info = yf.Ticker(t).fast_info
            # yfinance's FastInfo only returns camelCase keys via .get()/dict();
            # the snake_case names are exposed as attributes instead.
            price = info.last_price
            prev = info.previous_close
            year_high = info.year_high
            year_low = info.year_low
            market_cap = info.market_cap
            last_volume = info.last_volume
            chg_pct = (price - prev) / prev * 100 if price and prev else None
            row.update({
                "Price (INR)": round(price, 2) if price else None,
                "Chg %": round(chg_pct, 2) if chg_pct is not None else None,
                "52w High": round(year_high, 2) if year_high else None,
                "52w Low": round(year_low, 2) if year_low else None,
                "Market Cap (Cr)": round(market_cap / 1e7, 0) if market_cap else None,
                "Volume": last_volume,
            })
        except Exception:
            row.update({"Price (INR)": None, "Chg %": None, "52w High": None,
                         "52w Low": None, "Market Cap (Cr)": None, "Volume": None})
        rows.append(row)
    return pd.DataFrame(rows)


@st.cache_data(ttl=900, show_spinner="Fetching recent price history...")
def fetch_recent_closes(period="6mo"):
    data = yf.download(TICKERS, period=period, interval="1d", auto_adjust=True, progress=False)
    close = pd.DataFrame({t: data["Close"][t] for t in TICKERS}).dropna()
    return close


def build_corr_graph(close_df, threshold=CORR_THRESHOLD):
    """Same construction as build_adj() in LSTM&GNN FINAL.py, minus the
    Kipf-Welling normalisation (kept raw here since this is for display,
    not for feeding into the model)."""
    ret = close_df.pct_change().dropna()
    corr = ret.corr().values
    return corr, ret


