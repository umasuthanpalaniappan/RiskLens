"""
RiskLens — Streamlit Dashboard
===============================
Two-page app for the VolGraph / RiskLens project (LSTM + Dynamic GNN
volatility predictor for 10 Indian banking stocks).

Page 1 (default, "Overview"):
    Live basic details for each of the 10 banking stocks — price,
    change, 52-week range, market cap — plus a quick live correlation
    snapshot.

Page 2 ("Model", hidden behind the "Next ->" button on Page 1):
    LSTM vs LSTM+GNN results, the 4 plots generated by
    "LSTM&GNN FINAL.py" (read from OUTPUT/), and a live correlation
    graph built the same way the model builds its dynamic adjacency
    matrix (Pearson corr, threshold 0.65, Kipf-Welling normalisation).

Navigation is manual (st.session_state), not Streamlit's built-in
multipage sidebar — so Page 2 is only reachable by clicking "Next ->"
on Page 1. There is no sidebar link exposing it directly.

Run with:
    streamlit run app.py
"""

