# PAGE 1 — Overview
# ─────────────────────────────────────────────────────────────
def render_overview():
    st.title("📈 RiskLens — Indian Banking Sector")
    st.caption(
        "Volatility & risk dashboard for 10 NSE banking stocks. "
        "This page shows current market snapshot only — the LSTM + Graph "
        "Neural Network volatility model lives on the next page."
    )

    df = fetch_overview()
    st.dataframe(
        df.style.format({
            "Price (INR)": "{:.2f}", "Chg %": "{:+.2f}%",
            "52w High": "{:.2f}", "52w Low": "{:.2f}",
            "Market Cap (Cr)": "{:,.0f}", "Volume": "{:,.0f}",
        }, na_rep="—")
        .map(lambda v: "color: #276749" if isinstance(v, float) and v > 0
             else ("color: #9B2226" if isinstance(v, float) and v < 0 else ""),
             subset=["Chg %"]),
        use_container_width=True, hide_index=True,
    )

    st.markdown("---")
    col1, col2 = st.columns([3, 2])

    with col1:
        st.subheader("Price trend (6 months, rebased to 100)")
        try:
            close = fetch_recent_closes()
            rebased = close / close.iloc[0] * 100
            rebased.columns = [t.replace(".NS", "") for t in rebased.columns]
            fig = px.line(rebased, labels={"value": "Rebased price", "index": "Date", "variable": "Stock"},
                          render_mode="svg")
            fig.update_layout(height=380, legend_title_text="", margin=dict(l=10, r=10, t=20, b=10))
            st.plotly_chart(fig, use_container_width=True)
        except Exception as e:
            st.info(f"Couldn't load price history right now ({e}).")

    with col2:
        st.subheader("Pick a stock")
        sel = st.selectbox("Stock", TICKERS, format_func=lambda t: f"{NAMES[t]} ({t.replace('.NS', '')})")
        row = df[df["Ticker"] == sel.replace(".NS", "")]
        if not row.empty:
            r = row.iloc[0]
            st.metric(NAMES[sel], f"₹{r['Price (INR)']:.2f}" if pd.notna(r["Price (INR)"]) else "—",
                       f"{r['Chg %']:+.2f}%" if pd.notna(r["Chg %"]) else None)
            st.caption(f"52w range: ₹{r['52w Low']:.0f} – ₹{r['52w High']:.0f}" if pd.notna(r["52w Low"]) else "")
            st.caption("PSU cluster stock" if sel in PSU_CLUSTER else "Private-sector stock")

    st.markdown("---")
    left, right = st.columns([4, 1])
    with left:
        st.caption("Ready to see how the LSTM + GNN model predicts volatility across this sector?")
    with right:
        st.button("Next →", type="primary", use_container_width=True,
                   on_click=goto, args=("model",))


# ─────────────────────────────────────────────────────────────
# PAGE 2 — LSTM + GNN Model
# ─────────────────────────────────────────────────────────────
def render_model():
    top_left, top_right = st.columns([1, 5])
    with top_left:
        st.button("← Back", on_click=goto, args=("overview",))

    st.title("🧠 LSTM + Dynamic GNN — Volatility Model")
    st.caption(
        "Stage 1: an LSTM reads a 20-day window of 84 engineered features per stock. "
        "Stage 2: a dynamic Graph Neural Network lets stocks exchange information with "
        "correlated peers via a rolling 60-day correlation graph (edge threshold = "
        f"{CORR_THRESHOLD}), gated per stock so the GNN only contributes when it helps."
    )

    st.subheader("Test-set results: LSTM only vs LSTM + Gated GNN")
    m1, m2, m3, m4 = st.columns(4)
    m1.metric("Direction Accuracy — LSTM", f"{LSTM_DIR_OVERALL:.1%}")
    m2.metric("Direction Accuracy — LSTM+GNN", f"{GNN_DIR_OVERALL:.1%}",
               f"{(GNN_DIR_OVERALL - LSTM_DIR_OVERALL):+.1%}")
    m3.metric("R² — LSTM only", f"{LSTM_R2_OVERALL:.3f}")
    m4.metric("Correlation — LSTM only", f"{LSTM_CORR_OVERALL:.3f}")
    st.caption(
        "R² / correlation are only tracked for the LSTM-only baseline in the saved run; "
        "the LSTM+GNN combined R²/correlation are computed each time the training script "
        "runs but aren't persisted — only direction accuracy was locked per stock below."
    )

    st.subheader("Per-stock direction accuracy")
    rows = []
    for t in TICKERS:
        rows.append({
            "Stock": NAMES[t],
            "Cluster": "PSU" if t in PSU_CLUSTER else "Private",
            "LSTM dir. acc.": LSTM_RESULTS[t]["dir"],
            "LSTM+GNN dir. acc.": LOCKED_GNN_DIR[t],
            "Δ": LOCKED_GNN_DIR[t] - LSTM_RESULTS[t]["dir"],
        })
    perf_df = pd.DataFrame(rows).sort_values("Δ", ascending=False)
    st.dataframe(
        perf_df.style.format({"LSTM dir. acc.": "{:.1%}", "LSTM+GNN dir. acc.": "{:.1%}", "Δ": "{:+.1%}"})
        .map(lambda v: "color: #276749" if isinstance(v, float) and v > 0
             else ("color: #9B2226" if isinstance(v, float) and v < 0 else ""), subset=["Δ"]),
        use_container_width=True, hide_index=True,
    )
    st.caption(
        "GNN helps PSU-cluster stocks (SBIN, KOTAKBANK) that benefit from correlated "
        "neighbours, and tends to hurt ICICIBANK, which is already accurate on its own — "
        "consistent with it trading closer to informational efficiency."
    )

    st.markdown("---")
    st.subheader("Training run plots")
    st.caption(f"Read directly from `{os.path.relpath(OUTPUT_DIR, os.path.dirname(__file__))}/` — "
               "rerun `LSTM&GNN FINAL.py` to regenerate these.")

    plot_files = [
        ("plot_1_lstm_direction.png", "LSTM-only direction accuracy per stock"),
        ("plot_2_lstm_vs_gnn.png", "LSTM vs LSTM+GNN direction accuracy"),
        ("plot_2b_change_only.png", "Per-stock accuracy change from adding the GNN"),
        ("plot_3_last_day_vol.png", "Latest test day: current vs predicted vs actual volatility"),
        ("plot_4_edge_density.png", "Dynamic graph edge density over time"),
    ]
    for fname, caption in plot_files:
        path = os.path.join(OUTPUT_DIR, fname)
        if os.path.exists(path):
            st.image(path, caption=caption, use_container_width=True)
        else:
            st.info(f"{fname} not found in OUTPUT/ yet — run the training script to generate it.")

    st.markdown("---")
    st.subheader("Live correlation graph (same rule the model uses to build edges)")
    st.caption(
        f"Pearson correlation of daily returns over the last 6 months, edges kept where "
        f"|corr| ≥ {CORR_THRESHOLD}. The trained model rebuilds this graph on a rolling "
        "60-day window and re-normalises it (Kipf & Welling) before each prediction — "
        "this is a live, simplified snapshot for display."
    )
    try:
        close = fetch_recent_closes()
        corr, _ = build_corr_graph(close)
        labels = [t.replace(".NS", "") for t in TICKERS]

        fig = go.Figure(data=go.Heatmap(
            z=corr, x=labels, y=labels, zmin=-1, zmax=1,
            colorscale="RdBu", reversescale=True,
            colorbar=dict(title="corr"),
        ))
        fig.update_layout(height=450, margin=dict(l=10, r=10, t=20, b=10))
        st.plotly_chart(fig, use_container_width=True)

        n_edges = int(((np.abs(corr) >= CORR_THRESHOLD).sum() - len(TICKERS)) / 2)
        st.caption(f"{n_edges} active edges right now at threshold {CORR_THRESHOLD}.")
    except Exception as e:
        st.info(f"Couldn't build the live correlation graph right now ({e}).")


# ─────────────────────────────────────────────────────────────
